"""Turn results/validated_em.json into the markdown tables in docs/validated_em.md."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = [os.path.join(ROOT, "results", f"validated_em_{d}.json")
           for d in ("text2sql", "vision", "graph")]


def load(paths):
    """Merge the per-domain result files written by run_validated_em.py."""
    merged = {}
    for path in paths:
        if not os.path.exists(path):
            print(f"<!-- missing: {path} -->")
            continue
        body = json.load(open(path))
        meta = body.pop("metadata", {})
        merged.setdefault("metadata", {}).update(meta)
        merged.update(body)
    return merged


def collect(payload):
    """-> {section_title: {case_name: {method: mae}}} in report order."""
    out = {}
    t2s = payload.get("text2sql", {})
    for protocol, title in (("source", "Text2SQL -- protocol A (labeled source split)"),
                            ("holdout", "Text2SQL -- protocol B (target holdout)")):
        block = {ds: body[protocol]["rows"] for ds, body in t2s.items()
                 if protocol in body}
        if block:
            out[title] = block
    if payload.get("vision"):
        out["Image classification"] = {k: v["rows"]
                                       for k, v in payload["vision"].items()}
    if payload.get("graph"):
        out["Node classification"] = {k: v["rows"]
                                      for k, v in payload["graph"].items()}
    return out


def table(block, only=None, drop_prefix=None):
    cases = list(block)
    methods = [m for m in next(iter(block.values()))
               if (only is None or any(m.startswith(p) for p in only))
               and (drop_prefix is None or not m.startswith(drop_prefix))]
    rows = []
    for m in methods:
        vals = [block[c].get(m) for c in cases]
        if any(v is None for v in vals):
            continue
        rows.append((m, vals, sum(vals) / len(vals)))
    if not rows:
        return ""
    best = [min(r[1][k] for r in rows) for k in range(len(cases))]
    best_mean = min(r[2] for r in rows)

    head = "| method | " + " | ".join(cases) + " | **mean** |"
    sep = "|---" * (len(cases) + 2) + "|"
    lines = [head, sep]
    for name, vals, mean in rows:
        cells = [f"**{v:.2f}**" if abs(v - best[k]) < 1e-9 else f"{v:.2f}"
                 for k, v in enumerate(vals)]
        mcell = f"**{mean:.2f}**" if abs(mean - best_mean) < 1e-9 else f"{mean:.2f}"
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {mcell} |")
    return "\n".join(lines)


def main(paths=None):
    paths = paths or DEFAULT
    payload = load(paths)
    sections = collect(payload)
    print("<!-- generated by experiments/report_validated_em.py -->")
    meta = payload.get("metadata", {})
    print(f"\nMAE in accuracy points (x100), lower is better. Best per column in bold. "
          f"Budgets {meta.get('budgets')}, expert accuracy {meta.get('expert_accuracy')}, "
          f"IG candidates {meta.get('ig_candidates')}, IG sweeps {meta.get('ig_iters')}.\n")
    for title, block in sections.items():
        print(f"\n### {title}\n")
        print("**Estimators and the judge budget**\n")
        print(table(block, drop_prefix="ABL "))
        abl = table(block, only=["ABL "])
        if abl:
            print(f"\n**Ablations at the largest budget**\n")
            print(abl)
    print()


if __name__ == "__main__":
    main(sys.argv[1:] or None)
